public class datatypes{
    public static void main(String[] args){
        char ch = 'a';
        System.out.println(ch);

        int b = 7;
        System.out.println(b);

        String str = "parth";
        System.out.println(str);

        boolean var = true;
        System.out.println(var);

        float price = 6.7f;
        System.out.println(price);
    }
}